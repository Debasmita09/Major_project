        <h1>Top 10 Interview Questions & Answers</h1>
        <p>Interviews can be nerve-wracking, but preparing well can boost your confidence. Here are the 10 most common interview questions along with sample answers to help you ace your next job interview.</p>
        
        <h2 class="question">1. Tell me about yourself.</h2>
        <p class="tip">💡 Tip: Keep it professional. Give a brief summary of your background, experience, and skills relevant to the job.</p>
        <div class="answer">"I have a background in digital marketing with over five years of experience in SEO, social media management, and content strategy..."</div>
        
        <h2 class="question">2. Why do you want to work here?</h2>
        <p class="tip">💡 Tip: Show that you’ve researched the company and align your values with theirs.</p>
        <div class="answer">"I admire [Company Name] for its innovation and commitment to customer satisfaction..."</div>
        
        <h2 class="question">3. What are your strengths?</h2>
        <p class="tip">💡 Tip: Choose strengths relevant to the job and back them up with examples.</p>
        <div class="answer">"One of my greatest strengths is my problem-solving ability..."</div>
        
        <h2 class="question">4. What is your biggest weakness?</h2>
        <p class="tip">💡 Tip: Be honest but show how you’re improving.</p>
        <div class="answer">"I used to struggle with public speaking, but I’ve been actively working on it..."</div>
        
        <h2 class="question">5. Where do you see yourself in five years?</h2>
        <p class="tip">💡 Tip: Align your goals with the company’s growth but show ambition.</p>
        <div class="answer">"In five years, I see myself in a leadership role..."</div>
        
        <h2 class="question">6. Why should we hire you?</h2>
        <p class="tip">💡 Tip: Highlight what makes you unique and how you can add value.</p>
        <div class="answer">"I have the skills and experience required for this role, but what sets me apart..."</div>
        
        <h2 class="question">7. Can you describe a challenging situation at work and how you handled it?</h2>
        <p class="tip">💡 Tip: Use the STAR method (Situation, Task, Action, Result).</p>
        <div class="answer">"At my last job, a critical client project was falling behind..."</div>
        
        <h2 class="question">8. How do you handle stress and pressure?</h2>
        <p class="tip">💡 Tip: Show that you stay calm and find solutions.</p>
        <div class="answer">"I prioritize tasks, break them into manageable steps..."</div>
        
        <h2 class="question">9. What do you know about our company?</h2>
        <p class="tip">💡 Tip: Research the company’s mission, values, and recent achievements.</p>
        <div class="answer">"I know that [Company Name] is a leader in [industry]..."</div>
        
        <h2 class="question">10. Do you have any questions for us?</h2>
        <p class="tip">💡 Tip: Always ask at least one question to show your interest.</p>
        <div class="answer">
            ✅ "What does success look like in this role?"<br>
            ✅ "Can you tell me more about the company culture?"<br>
            ✅ "What are the biggest challenges the team is currently facing?"
