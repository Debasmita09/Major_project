<div class="container">
    <h1>How to Write a Winning Resume</h1>
    <p>A well-crafted resume is your ticket to landing an interview. It should highlight your skills, experience, and achievements in a clear and concise manner. Follow these steps to create a resume that stands out.</p>

    <h2>1. Choose the Right Format</h2>
    <ul>
        <li>✅ <span class="highlight">Reverse Chronological:</span> Lists work experience from most recent to oldest. (Best for most job seekers)</li>
        <li>✅ <span class="highlight">Functional:</span> Focuses on skills rather than experience. (Good for career changers)</li>
        <li>✅ <span class="highlight">Combination:</span> A mix of both. (Best for professionals with diverse experience)</li>
    </ul>
    <div class="tip">💡 <strong>Tip:</strong> Use a reverse chronological format if you have steady work experience.</div>

    <h2>2. Write a Strong Header</h2>
    <p>Your resume should start with:</p>
    <ul>
        <li>📌 Full Name</li>
        <li>📌 Phone Number</li>
        <li>📌 Email Address</li>
        <li>📌 LinkedIn Profile (if applicable)</li>
        <li>📌 Portfolio (for designers, developers, etc.)</li>
    </ul>
    <div class="example">
        <strong>Example:</strong><br>
        <p>John Doe<br>📍 New York, NY | 📞 (123) 456-7890 | 📧 johndoe@email.com | 🔗 linkedin.com/in/johndoe</p>
    </div>

    <h2>3. Craft a Powerful Summary or Objective</h2>
    <p>A resume summary (for experienced professionals) or an objective statement (for entry-level job seekers) should briefly describe your skills and career goals.</p>
    <div class="example">
        <strong>Example Summary:</strong><br>
        <p>"Results-driven marketing specialist with 5+ years of experience in digital advertising, SEO, and content strategy. Proven ability to increase online engagement by 50% and generate high-quality leads."</p>
    </div>
    <div class="example">
        <strong>Example Objective:</strong><br>
        <p>"Recent graduate in Computer Science with strong programming skills in Python and Java. Seeking an entry-level software developer role to apply my knowledge in web development."</p>
    </div>

    <h2>4. Highlight Your Work Experience</h2>
    <p>List your previous jobs in reverse chronological order, including:</p>
    <ul>
        <li>📌 Job Title</li>
        <li>📌 Company Name</li>
        <li>📌 Location</li>
        <li>📌 Dates of Employment</li>
        <li>📌 Key Responsibilities & Achievements</li>
    </ul>
    <div class="example">
        <strong>Example:</strong><br>
        <p><strong>Digital Marketing Specialist</strong><br>ABC Marketing Agency | New York, NY | Jan 2020 – Present</p>
        <ul>
            <li>✅ Developed and executed SEO strategies, increasing website traffic by 40%.</li>
            <li>✅ Managed social media campaigns, boosting engagement by 60%.</li>
            <li>✅ Led a team of 5 marketing specialists to drive brand awareness.</li>
        </ul>
    </div>
    <div class="tip">💡 <strong>Tip:</strong> Use numbers and percentages to showcase achievements.</div>

    <h2>5. Showcase Your Skills</h2>
    <p>Include a skills section with relevant technical and soft skills.</p>
    <div class="example">
        <strong>Example:</strong><br>
        <p><strong>Technical Skills:</strong></p>
        <ul>
            <li>✅ SEO & Digital Marketing</li>
            <li>✅ Google Ads & Analytics</li>
            <li>✅ HTML, CSS, JavaScript</li>
        </ul>
        <p><strong>Soft Skills:</strong></p>
        <ul>
            <li>✅ Leadership & Communication</li>
            <li>✅ Problem-Solving</li>
            <li>✅ Time Management</li>
        </ul>
    </div>

    <h2>6. Add Education & Certifications</h2>
    <div class="example">
        <strong>Example:</strong><br>
        <p>🎓 <strong>Bachelor of Science in Computer Science</strong><br>XYZ University, 2023</p>
        <p>📜 <strong>Certifications:</strong></p>
        <ul>
            <li>Google Ads Certification</li>
            <li>Project Management Professional (PMP)</li>
        </ul>
    </div>

    <h2>7. Format Your Resume Properly</h2>
    <ul>
        <li>✅ Keep it 1 page (2 pages max for experienced professionals).</li>
        <li>✅ Use a clean, professional font (Arial, Calibri, Times New Roman).</li>
        <li>✅ Use bullet points for easy reading.</li>
        <li>✅ Save as PDF before submitting.</li>
    </ul>

    <h2>8. Tailor Your Resume for Each Job</h2>
    <p>📌 Read the job description carefully.</p>
    <p>📌 Use keywords from the job posting to pass Applicant Tracking Systems (ATS).</p>
    <p>📌 Adjust your skills and achievements to match the role.</p>

    <h2>9. Proofread & Get Feedback</h2>
    <ul>
        <li>✅ Check for spelling and grammar errors.</li>
        <li>✅ Ask a friend, mentor, or career coach to review it.</li>
        <li>✅ Use online tools like Grammarly or Hemingway Editor for clarity.</li>
    </ul>

    <h2>Final Thoughts</h2>
    <p>A winning resume is clear, concise, and customized for each job. Follow these tips to make yours stand out! 🚀</p>

